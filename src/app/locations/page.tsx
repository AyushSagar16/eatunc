import { campusToday, getHoursForLocations, getLocations, locationPath, shiftDate } from '@/lib/campus'
import type { Location, LocationHours } from '@/lib/campus'
import { breadcrumbList, canonical } from '@/lib/seo'
import { Breadcrumbs, CampusPage, Card, IconTile, PageHeading } from '@/components/campus/CampusChrome'
